    tenant_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    recipient_key VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    recipient_user_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NULL,
    recipient_role_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    notification_type VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    title VARCHAR(255) NOT NULL,
    content VARCHAR(2000) NOT NULL,
    contract_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NULL,
    approval_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NULL,
    dedupe_key VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    delivery_status VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
